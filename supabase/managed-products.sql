-- Run once in Supabase SQL Editor before using product creation in /admin/produtos.
create table if not exists public.managed_products (
  id bigint generated by default as identity (start with 1000000) primary key,
  business text not null check (business in ('bijuteria', 'gravacoes')),
  slug text not null unique,
  name text not null,
  category text not null check (category in ('Anéis', 'Brincos', 'Colares', 'Pulseiras', 'Gravações')),
  category_name text not null,
  price numeric(10, 2) not null check (price >= 0),
  description text not null,
  images text[] not null default '{}',
  details text[] not null default '{}',
  materials text[] not null default '{}',
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.managed_products enable row level security;
drop policy if exists "Admins manage custom products" on public.managed_products;
create policy "Admins manage custom products" on public.managed_products
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('managed-product-images', 'managed-product-images', true, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = true, file_size_limit = 8388608, allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

drop policy if exists "Public can view managed product images" on storage.objects;
create policy "Public can view managed product images" on storage.objects
  for select to public using (bucket_id = 'managed-product-images');

alter table public.admin_audit_log drop constraint if exists admin_audit_log_action_check;
alter table public.admin_audit_log add constraint admin_audit_log_action_check check (action in (
  'publish','hide','publish_filtered','hide_filtered',
  'best_seller_add','best_seller_remove',
  'best_seller_add_filtered','best_seller_remove_filtered',
  'new_arrival_add','new_arrival_remove',
  'new_arrival_add_filtered','new_arrival_remove_filtered',
  'managed_product_create'
));
